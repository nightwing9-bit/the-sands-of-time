using System.Globalization;
using System.Text;
using Revenant.Scenario;

namespace Revenant.Intelligence;

/// <summary>
/// Seeded, project-generated, genuinely labeled synthetic transfers in PaySim's column layout (plus <c>scenarioId</c>), so the SAME
/// ETL and feature builder process fixture and PaySim files. It is a LIMITED FALLBACK, not PaySim: every metric computed from it must
/// be labeled "project synthetic fixture". It is independent of the Friday Ring seeds and must never be presented as an independent
/// Friday Ring evaluation. All arithmetic is integer, so the bytes depend only on the seed.
/// <para>
/// Shape: 700 "customer" accounts, each active for a 12-step window with 4 transfers; 40 fraud scenarios of 3 mule accounts x 2
/// drain-like transfers inside 6 steps (15 percent of fraud rows deliberately look ordinary, 3 percent of ordinary rows drain a balance,
/// 5 percent of ordinary rows come from an empty account); about 150 CASH_OUT and 50 PAYMENT rows that the ETL must filter. Post-payment balance
/// and <c>isFlaggedFraud</c> columns are filled realistically so tests can prove they are ignored.
/// </para>
/// </summary>
public static class RiskFixture
{
    public const long DefaultSeed = 8101;
    public const int FirstStep = 1;
    public const int LastStep = 240;

    public static readonly RiskSourceDescription Description = new(
        "project-synthetic-fixture",
        "risk-fixture/1 (seeded, labeled, PaySim-shaped)",
        "Generated by this repository; no external dataset, no external license. Not PaySim.",
        [
            "Project synthetic fixture: every metric computed from it is a fixture-only metric, not PaySim and not independent validation.",
            "Not a Friday Ring evaluation: the Friday Ring scenario seeds are unrelated and no Friday Ring run is trained on or scored here.",
            "Transfers only (USD, 100 minor units per nominal unit); non-transfer rows are generated to be filtered.",
            "Fraud labels come from the generator's scenario type, not from any real-world finding.",
        ]);

    public static byte[] GenerateCsv(long seed = DefaultSeed)
    {
        var rows = new List<(int Step, int Order, string Line)>();
        var order = 0;
        var group = 0;

        var legit = SeededRandom.ForStream(seed, 1);
        for (var a = 0; a < 700; a++)
        {
            var start = legit.NextInt(FirstStep, LastStep - 12 + 2);
            var g = ++group;
            for (var t = 0; t < 4; t++)
            {
                var step = Math.Min(LastStep, start + legit.NextInt(0, 12));
                long balance = legit.NextInt(0, 100) < 5 ? 0 : Balance(legit);
                long amount;
                if (balance == 0)
                {
                    amount = legit.NextInt(500, 50001);
                }
                else
                {
                    var permille = legit.NextInt(0, 100) < 3 ? legit.NextInt(900, 1001) : legit.NextInt(5, 501);
                    amount = Math.Max(1, balance * permille / 1000);
                }
                rows.Add((step, order, Line(step, "TRANSFER", amount, $"C{1_000_000 + a}", balance, $"C{5_000_000 + legit.NextInt(0, 2_000_000)}", false, g)));
                order++;
            }
        }

        var fraud = SeededRandom.ForStream(seed, 2);
        for (var s = 0; s < 40; s++)
        {
            var start = fraud.NextInt(FirstStep, LastStep - 6 + 2);
            var g = ++group;
            for (var m = 0; m < 3; m++)
            {
                for (var t = 0; t < 2; t++)
                {
                    var step = Math.Min(LastStep, start + fraud.NextInt(0, 6));
                    var balance = Balance(fraud) * 3;
                    var permille = fraud.NextInt(0, 100) < 15 ? fraud.NextInt(50, 501) : fraud.NextInt(850, 1001);
                    var amount = Math.Max(1, balance * permille / 1000);
                    rows.Add((step, order, Line(step, "TRANSFER", amount, $"C{2_000_000 + s * 10 + m}", balance, $"C{7_000_000 + fraud.NextInt(0, 500_000)}", true, g)));
                    order++;
                }
            }
        }

        var other = SeededRandom.ForStream(seed, 3);
        for (var i = 0; i < 200; i++)
        {
            var step = other.NextInt(FirstStep, LastStep + 1);
            var type = i % 4 == 0 ? "PAYMENT" : "CASH_OUT";
            var balance = Balance(other);
            rows.Add((step, order, Line(step, type, Math.Max(1, balance * other.NextInt(10, 900) / 1000), $"C{3_000_000 + i}", balance, $"M{9_000_000 + i}", i % 7 == 0, ++group)));
            order++;
        }

        var csv = new StringBuilder("step,type,amount,nameOrig,oldbalanceOrg,newbalanceOrig,nameDest,oldbalanceDest,newbalanceDest,isFraud,isFlaggedFraud,scenarioId\n");
        foreach (var r in rows.OrderBy(r => r.Step).ThenBy(r => r.Order))
        {
            csv.Append(r.Line).Append('\n');
        }
        return Encoding.UTF8.GetBytes(csv.ToString());
    }

    /// <summary>Integer-only balance in minor units: a 3-digit mantissa times 10^1..10^4 (about 10 to 99,900 major units).</summary>
    private static long Balance(SeededRandom random)
    {
        long mantissa = random.NextInt(100, 1000);
        var scale = random.NextInt(1, 5);
        for (var i = 0; i < scale; i++)
        {
            mantissa *= 10;
        }
        return mantissa;
    }

    private static string Money(long minor) => (minor / 100m).ToString("0.00", CultureInfo.InvariantCulture);

    private static string Line(int step, string type, long amount, string orig, long oldBalance, string dest, bool fraud, int group)
    {
        var newOrig = Math.Max(0, oldBalance - amount);
        var destOld = (amount * 7) % 1_000_000;
        // isFlaggedFraud mimics PaySim's rule (very large transfers); it is deliberately NOT the label.
        var flagged = amount >= 20_000_000 ? 1 : 0;
        return string.Join(',', step.ToString(CultureInfo.InvariantCulture), type, Money(amount), orig, Money(oldBalance), Money(newOrig), dest,
            Money(destOld), Money(destOld + amount), fraud ? "1" : "0",
            flagged.ToString(CultureInfo.InvariantCulture), "G" + group.ToString("0000", CultureInfo.InvariantCulture));
    }
}
